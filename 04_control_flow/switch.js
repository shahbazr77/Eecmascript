// switch cases

let fruit = "banana";

switch(fruit){
    case "apple":
        console.log("apple");
        break;
    case "banana":
        console.log("banana");
        break;
    case "graps":
        console.log("graps");
        break;
    case "orange":
        console.log("orange");
        break;
    default:
        console.log("no match found");
        
}   